#!/usr/bin/env node
// Writes app/sw.js with the list of files to keep for offline use.
// Run after adding, removing or changing any file under app/:  npm run sw
// `--check` exits non-zero if app/sw.js is out of date (used in CI).
import { readdirSync, readFileSync, writeFileSync, statSync, existsSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { join, relative } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('../app/', import.meta.url));
const walk = (dir) => readdirSync(dir).flatMap((n) => { const p = join(dir, n); return statSync(p).isDirectory() ? walk(p) : [p]; });
const files = walk(root).map((p) => relative(root, p).split('\\').join('/'))
  .filter((f) => f !== 'sw.js' && !f.startsWith('audio/kn/') && !f.endsWith('.md') && !f.endsWith('.DS_Store')).sort();
const h = createHash('sha256'); for (const f of files) { h.update(f); h.update(readFileSync(join(root, f))); }
const version = h.digest('hex').slice(0, 12);

const sw = `// Generated by scripts/build-sw.mjs. Do not edit by hand.
const VERSION = '${version}';
const CORE = 'kk-core-' + VERSION, AUDIO = 'kk-audio-v1';
const ASSETS = ${JSON.stringify(['./'].concat(files), null, 0)};

self.addEventListener('install', (e) => {
  e.waitUntil(caches.open(CORE).then((c) => c.addAll(ASSETS)).then(() => self.skipWaiting()));
});
self.addEventListener('activate', (e) => {
  e.waitUntil(caches.keys().then((keys) => Promise.all(keys.filter((k) => k.startsWith('kk-core-') && k !== CORE).map((k) => caches.delete(k)))).then(() => self.clients.claim()));
});
self.addEventListener('fetch', (e) => {
  const req = e.request; if (req.method !== 'GET') return;
  const url = new URL(req.url); if (url.origin !== location.origin) return;
  // Audio clips: keep each one the first time it is heard.
  if (url.pathname.includes('/audio/kn/')) {
    e.respondWith(caches.open(AUDIO).then((c) => c.match(req).then((hit) => hit || fetch(req).then((res) => { if (res.ok) c.put(req, res.clone()); return res; }))));
    return;
  }
  // Everything else: answer from the cache, fall back to the network.
  e.respondWith(caches.match(req, { ignoreSearch: true }).then((hit) => hit || fetch(req).catch(() => caches.match('./'))));
});
`;
const out = join(root, 'sw.js');
if (process.argv.includes('--check')) {
  if (!existsSync(out) || readFileSync(out, 'utf8') !== sw) { console.error('app/sw.js is out of date. Run: npm run sw'); process.exit(1); }
  console.log('sw.js is up to date (' + files.length + ' files, version ' + version + ')');
} else { writeFileSync(out, sw); console.log('wrote app/sw.js: ' + files.length + ' files, version ' + version); }
